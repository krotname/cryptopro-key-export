namespace CryptoProExport
{
    /// <summary>
    /// Чем объяснить список без единого контейнера — прямо в самом списке, а не только в
    /// журнале (ROADMAP, P2, п. 7). Журнал теперь свёрнут по умолчанию, и пустое окно иначе
    /// не объясняет себя ничем.
    ///
    /// Считать нужно именно строки с контейнерами. Строка устройства («только носитель»)
    /// список формально наполняет, но показывать в нём по-прежнему нечего — а причин у этого
    /// четыре, и действия у них разные:
    ///   • носителя нет вовсе — вставить;
    ///   • носитель вставлен, но ни одна библиотека PKCS#11 его не показала;
    ///   • носитель прочитан, а контейнеров на нём нет — искать не здесь;
    ///   • обход сорвался ошибкой — «пусто» тут неизвестно, а не доказано.
    /// Раньше всё это было видно только в журнале (замечания Codex на PR #83).
    ///
    /// Правило вынесено из окна в Core сознательно: так его проверяют тесты, как и таблицу
    /// <see cref="ActionAvailability"/>.
    /// </summary>
    public static class ListEmptyHint
    {
        /// <summary>Носителя нет: считыватель пуст, не подключён или PC/SC его не видит.</summary>
        public const string NoReaderKey = "list.empty.noreader";

        /// <summary>Носитель вставлен, но читать его нечем: библиотеки PKCS#11 не нашлось.</summary>
        public const string NoLibraryKey = "list.empty.nolibrary";

        /// <summary>Носитель прочитан, но ключевых контейнеров на нём нет.</summary>
        public const string NoContainerKey = "list.empty.nocontainer";

        /// <summary>Опрос сорвался: часть носителей прочитать не удалось, и «пусто» тут неправда.</summary>
        public const string ScanFailedKey = "list.empty.scanfailed";

        /// <summary>
        /// Стоит ли за строкой списка настоящий контейнер. Строка «только устройство» и
        /// сертификат-сирота (AGENTS п. 30) — не контейнеры: за первой контейнера ещё нет,
        /// за вторым нет вовсе. Обе наполняют список, но показывать по-прежнему нечего, и
        /// считать их «есть что показать» нельзя (замечание Codex на PR #83).
        /// </summary>
        public static bool IsContainerRow(SelectedRow row) =>
            row is not (SelectedRow.None or SelectedRow.Device or SelectedRow.TokenCertificateOnly);

        /// <summary>
        /// Ключ объяснения или <c>null</c>, если объяснять нечего — контейнеры в списке есть.
        /// </summary>
        /// <param name="containerRows">
        /// Строки с контейнерами. Строки «только устройство» сюда не входят: они и есть тот
        /// случай, который надо объяснить, — <c>PcscReaders.Uncovered</c> и пустой слот PKCS#11
        /// добавляют такую строку, и по общему числу строк объяснение никогда бы не показалось.
        /// </param>
        /// <param name="carriers">
        /// Носители, а не считыватели: пустой слот PC/SC виден системе всегда, но строки не
        /// даёт — по числу считывателей он объяснялся бы «нет библиотеки» вместо «вставьте».
        /// </param>
        /// <param name="pkcs11Tokens">
        /// Сколько носителей показала хоть одна библиотека PKCS#11. Ноль при вставленном
        /// носителе — это и есть «библиотеки для него нет»; иначе носитель прочитан, и
        /// причина другая: контейнеров на нём нет.
        /// </param>
        /// <param name="scanFailed">
        /// Хотя бы один обход носителя сорвался ошибкой. Тогда «контейнеров нет» — неправда:
        /// у Рутокен Lite и JaCarta LT контейнеры КриптоПро видны только прямым APDU, и его
        /// ошибка означает «неизвестно» (замечание Codex на PR #83). Ошибка перекрывает
        /// остальные причины: пока опрос не прошёл целиком, судить об остальном нельзя.
        /// </param>
        /// <param name="uncoveredCarriers">
        /// Носители, которых не показала ни одна библиотека PKCS#11. Достаточно одного:
        /// прочитанный соседний токен не доказывает, что прочитаны все, — иначе на машине с
        /// двумя картами непокрытая объяснялась бы «контейнеров нет» вместо «нет библиотеки»
        /// (замечание Codex на PR #83).
        /// </param>
        public static string KeyFor(int containerRows, int carriers, int pkcs11Tokens,
                                    int uncoveredCarriers = 0, bool scanFailed = false)
        {
            if (containerRows > 0) return null;
            if (scanFailed) return ScanFailedKey;
            if (uncoveredCarriers > 0) return NoLibraryKey;
            if (carriers <= 0 && pkcs11Tokens <= 0) return NoReaderKey;
            return pkcs11Tokens > 0 ? NoContainerKey : NoLibraryKey;
        }
    }
}
